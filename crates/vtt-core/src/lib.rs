//! # vtt-core — домен виртуального настольного стола
//!
//! Чистая логика без ввода-вывода, сети и графики. Здесь живут:
//!
//! - [`ids`] — идентификаторы сущностей и игроков;
//! - [`geom`] — минимальная 2D-геометрия;
//! - [`grid`] — сетка, снап, измерение дистанций (5e / 3.5 / hex);
//! - [`dice`] — парсер нотации бросков и детерминированный роллер;
//! - [`entities`] — персонажи, монстры, эффекты, состояния, токены;
//! - [`rules`] — расчёт характеристик по правилам 5e/5.5e (полуавтомат);
//! - [`scene`] — сцены, стены, свет, туман и проверка линии видимости;
//! - [`permissions`] — роли и права;
//! - [`content`] — заготовка компендиума (заклинания, предметы, монстры).
//!
//! ## Принципы
//!
//! 1. **Данные, а не поведение.** Сущности — простые структуры с `serde`.
//! 2. **Детерминизм.** Всё, что бросает кубики, принимает [`rng::Rng`] снаружи —
//!    поэтому броски воспроизводимы в тестах и при переигровке.
//! 3. **Полуавтомат.** [`rules`] вычисляет и *объясняет* результат (см. [`rules::Probe`]),
//!    но не применяет его: решение остаётся за ГМом.
//! 4. **Ноль тяжёлых зависимостей.** Только `serde`; сборка крейта — секунды.
//!
//! ## Чего здесь намеренно нет
//!
//! Рендера, сети, файлов, времени, потоков. Это слои выше:
//! `vtt-proto` (сообщения), `vtt-server` (авторитарное состояние),
//! `vtt-net` (транспорт), `vtt-app` (сборка и CLI).

