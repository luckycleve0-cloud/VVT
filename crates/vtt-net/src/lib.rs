//! # vtt-net — транспорт
//!
//! Два слоя:
//!
//! - [`codec`] — как сообщение превращается в байты (длина + JSON);
//! - [`tcp`] — как байты едут между ПК ГМа и игроками в локальной сети.
//!
//! ## Почему TCP и почему сейчас
//!
//! Задача первого этапа — доказать, что модель «ГМ = сервер» работает end-to-end.
//! Для этого достаточно TCP в LAN: ноль зависимостей, понятные ошибки, работает
//! между двумя компьютерами в одной квартире/офисе уже сегодня.
//!
//! ## Что будет дальше (см. `docs/ROADMAP.md`)
//!
//! - `iroh`/QUIC: соединение по публичному ключу, hole punching, релей — чтобы
//!   работало через интернет без проброса портов;
//! - ненадёжные датаграммы для движения токенов (сейчас всё идёт надёжно,
//!   для LAN это нормально, для интернета — нет);
//! - передача ассетов чанками по хэшу.
//!
//! Транспорт намеренно ничего не знает о правилах игры: он возит
//! [`vtt_proto::ClientMsg`] и [`vtt_proto::ServerMsg`].

#![forbid(unsafe_code)]
